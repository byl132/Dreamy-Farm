local materialCache_ = {}

local function GetVColMaterial(cache, key)
    key = key or "diff"
    if materialCache_[key] then return materialCache_[key] end
    if not cache then return nil end
    local mat = Material:new()
    local technique = cache:GetResource("Technique", "Techniques/DiffVCol.xml")
    if not technique then
        technique = cache:GetResource("Technique", "Techniques/NoTextureUnlitVCol.xml")
    end
    if not technique then return nil end
    mat:SetTechnique(0, technique)
    materialCache_[key] = mat
    return mat
end

local function Clamp(v, a, b)
    if v < a then return a end
    if v > b then return b end
    return v
end

local function Cross(ax, ay, az, bx, by, bz)
    return ay * bz - az * by, az * bx - ax * bz, ax * by - ay * bx
end

local function Normalize(x, y, z)
    local len = math.sqrt(x * x + y * y + z * z)
    if len <= 0.00001 then return Vector3(0, 1, 0) end
    return Vector3(x / len, y / len, z / len)
end

local function VertexColorTree(mesh, x, y, z, variant)
    local h = Clamp(y / math.max(0.001, mesh.height), 0, 1)
    local r = math.sqrt(x * x + z * z) / math.max(0.001, mesh.radius)
    local leafShift = ((variant or 1) - 1) * 0.035
    if h < 0.62 and r < 0.26 then
        return Color(0.34 + leafShift, 0.20, 0.09, 1.0)
    end
    if h < 0.24 and r < 0.42 then
        return Color(0.40, 0.25, 0.12, 1.0)
    end
    local shade = 0.82 + 0.22 * h - 0.10 * r
    -- 〔场景真实化 2026-09-07〕树冠逐顶点噪声：明度/色相微变，打破整片同色的"塑料感"；
    -- 噪声由顶点坐标确定性推导（同树同观感，跨启动一致）
    local n = math.sin(x * 12.9898 + y * 78.233 + z * 37.719) * 43758.5453
    n = n - math.floor(n)
    local tone = 0.86 + 0.28 * n
    return Color((0.17 + leafShift) * tone, (0.42 * shade + leafShift) * (0.94 + 0.12 * n), 0.16 * (0.88 + 0.24 * n), 1.0)
end

local function VertexColorPond(mesh, x, y, z)
    local nx = x / math.max(0.001, mesh.sizeX * 0.5)
    local nz = z / math.max(0.001, mesh.sizeZ * 0.5)
    local edge = math.sqrt(nx * nx + nz * nz)
    local h = Clamp(y / math.max(0.001, mesh.height), 0, 1)
    if edge < 0.72 and h < 0.46 then
        return Color(0.14, 0.48, 0.60, 0.92)
    end
    if edge < 0.86 then
        return Color(0.22, 0.56, 0.64, 0.86)
    end
    return Color(0.45, 0.38, 0.24, 1.0)
end

local function BuildMesh(node, cache, mesh, colorFn, matKey)
    if not node or not cache or not mesh then return nil end
    local geom = node:CreateComponent("CustomGeometry")
    if not geom then return nil end
    geom:BeginGeometry(0, TRIANGLE_LIST)
    local p = mesh.positions
    local t = mesh.triangles
    for i = 1, #t, 3 do
        local ia = (t[i] - 1) * 3 + 1
        local ib = (t[i + 1] - 1) * 3 + 1
        local ic = (t[i + 2] - 1) * 3 + 1
        local ax, ay, az = p[ia], p[ia + 1], p[ia + 2]
        local bx, by, bz = p[ib], p[ib + 1], p[ib + 2]
        local cx, cy, cz = p[ic], p[ic + 1], p[ic + 2]
        local nx, ny, nz = Cross(bx - ax, by - ay, bz - az, cx - ax, cy - ay, cz - az)
        local normal = Normalize(nx, ny, nz)
        geom:DefineVertex(Vector3(ax, ay, az)); geom:DefineNormal(normal); geom:DefineColor(colorFn(mesh, ax, ay, az))
        geom:DefineVertex(Vector3(bx, by, bz)); geom:DefineNormal(normal); geom:DefineColor(colorFn(mesh, bx, by, bz))
        geom:DefineVertex(Vector3(cx, cy, cz)); geom:DefineNormal(normal); geom:DefineColor(colorFn(mesh, cx, cy, cz))
    end
    geom:Commit()
    local mat = GetVColMaterial(cache, matKey or "nature_vcol")
    if mat then geom:SetMaterial(0, mat) end
    return geom
end

function RealNatureModels.CreateTree(scene, cache, pos, scale, variant)
    if not scene or not cache or not pos then return nil end
    -- tree_e001 原始网格横向跨度大于高度，放在场景里会像倒树；这里只使用直立树变体。
    local treeNames = { "tree_c001", "tree_a001" }
    local idx = variant or (math.floor(math.abs(pos.x * 13 + pos.z * 7)) % #treeNames) + 1
    local meshName = treeNames[((idx - 1) % #treeNames) + 1]
    local mesh = MESHES[meshName]
    if not mesh then return nil end
    local node = scene:CreateChild("RealTree_" .. meshName)
    node.position = Vector3(pos.x, pos.y or 0, pos.z)
    local s = scale or 0.48
    node.scale = Vector3(s, s, s)
    local yaw = math.floor(math.abs(pos.x * 19 + pos.z * 23)) % 360
    node.rotation = Quaternion(yaw, Vector3.UP)
    local geom = BuildMesh(node, cache, mesh,
        function(m, x, y, z) return VertexColorTree(m, x, y, z, idx) end, "nature_vcol_tree")
    if not geom then
        node:Remove()
        return nil
    end
    -- 〔场景真实化 2026-09-07〕注册风摆（WeatherController 每帧按天气风强驱动）
    RealNatureModels.RegisterTree(node, yaw)
    return node
end

-- ============================================================
-- 〔场景真实化 2026-09-07〕树木实时天气反馈
--   · 风摆：RegisterTree 登记 → UpdateWeather 每帧按风力摆动（晴微风/雨强/台风狂摆）
--   · 树冠染色：树用独立共享材质 "nature_vcol_tree"，雨=湿叶深绿、雪霜=挂霜白绿、
--     旱=焦黄；MatDiffColor 乘法调和顶点色，一次设置全体树木生效
--   · 场景重建时必须 ClearTrees()（GameFlow.EnterGame 调用），防止悬空节点引用
-- ============================================================
local treeRegistry_ = {}
local treeClock_ = 0.0
local treeTintApplied_ = false

function RealNatureModels.RegisterTree(node, yaw)
    if not node then return end
    treeRegistry_[#treeRegistry_ + 1] = {
        node = node,
        yaw = yaw or 0,
        phase = math.random() * math.pi * 2,
        freq = 0.9 + math.random() * 0.7,
    }
end

function RealNatureModels.ClearTrees()
    treeRegistry_ = {}
    treeTintApplied_ = false
end

---@param dt number
---@param wind number 风强 0~1.5（晴 0.3 / 雨 0.7 / 台风 1.5）；由 WeatherController 每帧传入
---@param tint number[]|nil 树冠乘法色调 {r,g,b}，nil=恢复原色
function RealNatureModels.UpdateWeather(dt, wind, tint)
    treeClock_ = treeClock_ + (dt or 0.016)
    wind = wind or 0.3
    for _, t in ipairs(treeRegistry_) do
        local node = t.node
        if node then
            local swayP = math.sin(treeClock_ * t.freq + t.phase) * (1.4 * wind)
            local swayR = math.cos(treeClock_ * t.freq * 0.83 + t.phase) * (1.0 * wind)
            node.rotation = Quaternion(t.yaw, Vector3.UP)
                * Quaternion(swayP, Vector3.RIGHT)
                * Quaternion(swayR, Vector3.FORWARD)
        end
    end
    local wantTint = (tint ~= nil)
    if wantTint ~= treeTintApplied_ or wantTint then
        local mat = materialCache_["nature_vcol_tree"]
        if mat then
            local c = tint or { 1, 1, 1 }
            local tr = c[1] * 1.0
            local tg = c[2] * 1.0
            local tb = c[3] * 1.0
            mat:SetShaderParameter("MatDiffColor", Variant(Color(tr, tg, tb, 1.0)))
            treeTintApplied_ = wantTint
        end
    end
end

function RealNatureModels.CreatePond(scene, cache, center, radius, name)
    if not scene or not cache or not center then return nil end
    local mesh = MESHES.waterdish_a001
    if not mesh then return nil end
    local node = scene:CreateChild(name or "RealPondBasin")
    node.position = Vector3(center.x, center.y or 0.035, center.z)
    local rx = radius or 4.0
    -- 〔造型修复〕原 sz 用 rx*1.45 / sizeZ，使 Z 轴被错误压扁成 1.45 倍细长椭圆
    -- （sizeZ 仅 0.39m → 缩放比异常大），池塘整体被拉成怪异长条。
    -- 改为以半径 rx 同时约束 X/Z，保持 basin 原生近似椭率（sizeX≈1.75 / sizeZ≈0.39
    -- 已含长扁比例），仅按 rx 统一缩放，得到自然的水塘轮廓。
    local sx = (rx * 2.0) / math.max(0.001, mesh.sizeX)
    local sz = (rx * 2.0) / math.max(0.001, mesh.sizeZ)
    node.scale = Vector3(sx, 0.75, sz)
    local geom = BuildMesh(node, cache, mesh, VertexColorPond)
    if not geom then
        node:Remove()
        return nil
    end
    return node
end

